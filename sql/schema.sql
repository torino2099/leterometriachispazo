-- 1) Tabla principal ----------------------------------------------------
create table if not exists public.sorteos (
  id        bigint generated by default as identity primary key,
  concurso  int4  not null unique,
  r1        int4  not null check (r1 between 1 and 28),
  r2        int4  not null check (r2 between 1 and 28),
  r3        int4  not null check (r3 between 1 and 28),
  r4        int4  not null check (r4 between 1 and 28),
  r5        int4  not null check (r5 between 1 and 28),
  fecha     date  not null,
  horario   text  not null check (horario in ('15:00', '21:15')),
  -- un solo sorteo por fecha y horario
  constraint sorteos_fecha_horario_uk unique (fecha, horario),
  -- los 5 números deben ser distintos
  constraint sorteos_distintos check (
    r1 <> r2 and r1 <> r3 and r1 <> r4 and r1 <> r5 and
    r2 <> r3 and r2 <> r4 and r2 <> r5 and
    r3 <> r4 and r3 <> r5 and
    r4 <> r5
  )
);

create index if not exists sorteos_fecha_horario_idx
  on public.sorteos (fecha desc, horario desc);

-- 2) Administradores ---------------------------------------------------
-- Solo los usuarios listados aquí pueden escribir.
create table if not exists public.admins (
  user_id uuid primary key references auth.users (id) on delete cascade
);

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

-- 3) Row Level Security -----------------------------------------------
alter table public.sorteos enable row level security;
alter table public.admins  enable row level security;

drop policy if exists "lectura publica"   on public.sorteos;
drop policy if exists "admin inserta"     on public.sorteos;
drop policy if exists "admin actualiza"   on public.sorteos;
drop policy if exists "admin elimina"     on public.sorteos;

create policy "lectura publica" on public.sorteos
  for select to anon, authenticated
  using (true);

create policy "admin inserta" on public.sorteos
  for insert to authenticated
  with check (public.is_admin());

create policy "admin actualiza" on public.sorteos
  for update to authenticated
  using (public.is_admin())
  with check (public.is_admin());

create policy "admin elimina" on public.sorteos
  for delete to authenticated
  using (public.is_admin());

-- La tabla admins no tiene políticas: nadie la lee/escribe desde el cliente.
-- (La función is_admin() es security definer y sí puede consultarla.)

